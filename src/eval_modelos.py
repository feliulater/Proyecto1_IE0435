base_path = '/content/drive/MyDrive/Proyecto_arroz/Conjunto_datos/'

archivos = [
    'dataset1.csv',
    'dataset2.csv',
    'dataset3.csv',
    'dataset4.csv',
    'dataset5.csv'
]

ruta_modelo_salida = '/content/drive/MyDrive/Proyecto_arroz/mejor_modelo.joblib'


# ==============================
# FUNCIÓN PARA CARGAR CADA CSV
# ==============================

def cargar_csv(ruta):
    """
    Carga un CSV, corrige separadores si hace falta,
    elimina encabezados accidentales y deja solo valores numéricos.
    """

    df = pd.read_csv(ruta, header=None, sep=None, engine='python')

    # Si quedó todo en una sola columna, probablemente venía separado por ;
    if df.shape[1] == 1:
        df = df.iloc[:, 0].astype(str).str.split(';', expand=True)

    # Convertir todo a numérico
    df = df.apply(pd.to_numeric, errors='coerce')

    # Eliminar filas no numéricas, por ejemplo encabezados tipo pixel_0, pixel_1...
    df = df.dropna()

    # Convertir a enteros
    df = df.astype(int)

    return df


# ==============================
# CARGA Y UNIFICACIÓN
# ==============================

lista_dfs = []

print("--- Cargando y unificando archivos ---")

for archivo in archivos:
    ruta = os.path.join(base_path, archivo)

    try:
        df_temp = cargar_csv(ruta)

        columnas_esperadas = 128 * 128 + 1

        if df_temp.shape[1] != columnas_esperadas:
            print(f"Advertencia: {archivo} tiene {df_temp.shape[1]} columnas. Se esperaba {columnas_esperadas}. Se omitió.")
            continue

        lista_dfs.append(df_temp)
        print(f"{archivo} cargado correctamente. Filas: {df_temp.shape[0]}")

    except Exception as e:
        print(f"Error cargando {archivo}: {e}")


if not lista_dfs:
    raise ValueError("No se cargó ningún archivo. Revisa las rutas y nombres de los CSV.")


df = pd.concat(lista_dfs, ignore_index=True)

print("\nDataset unificado correctamente.")
print(f"Forma del dataset completo: {df.shape}")


# ==============================
# VERIFICACIÓN BÁSICA
# ==============================

columnas_esperadas = 128 * 128 + 1

if df.shape[1] != columnas_esperadas:
    raise ValueError(
        f"El dataset tiene {df.shape[1]} columnas, pero debería tener {columnas_esperadas}."
    )

valores_unicos = np.unique(df.values)

if not set(valores_unicos).issubset({0, 1}):
    print(f"Advertencia: el dataset contiene valores distintos de 0 y 1: {valores_unicos}")


# ==============================
# SEPARAR PIXELES Y ETIQUETA
# ==============================

X = df.iloc[:, :-1]
y = df.iloc[:, -1]

print("\nDistribución total de clases:")
print(y.value_counts().sort_index())


# ==============================
# DIVISIÓN 80% ENTRENAMIENTO / 20% PRUEBA
# ==============================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("\nDistribución en entrenamiento:")
print(y_train.value_counts().sort_index())

print("\nDistribución en prueba:")
print(y_test.value_counts().sort_index())

print(f"\nMuestras de entrenamiento: {len(X_train)}")
print(f"Muestras de prueba: {len(X_test)}")


# ==============================
# MODELOS A EVALUAR
# ==============================

modelos = {
    "SVM Lineal": Pipeline([
        ("scaler", StandardScaler()),
        ("modelo", SVC(kernel='linear', random_state=42))
    ]),

    "SVM RBF": Pipeline([
        ("scaler", StandardScaler()),
        ("modelo", SVC(kernel='rbf', random_state=42))
    ]),

    "KNN k=3": Pipeline([
        ("scaler", StandardScaler()),
        ("modelo", KNeighborsClassifier(n_neighbors=3))
    ]),

    "KNN k=5": Pipeline([
        ("scaler", StandardScaler()),
        ("modelo", KNeighborsClassifier(n_neighbors=5))
    ]),

    "KNN k=7": Pipeline([
        ("scaler", StandardScaler()),
        ("modelo", KNeighborsClassifier(n_neighbors=7))
    ]),

    "Naive Bayes": GaussianNB(),

    "Árbol de Decisión": DecisionTreeClassifier(
        random_state=42
    ),

    "Árbol de Decisión max_depth=5": DecisionTreeClassifier(
        random_state=42,
        max_depth=5
    ),

    "Random Forest": RandomForestClassifier(
        n_estimators=100,
        random_state=42
    )
}


# ==============================
# ENTRENAMIENTO Y EVALUACIÓN
# ==============================

print("\n--- Entrenando modelos y evaluando accuracy ---\n")

resultados = {}

for nombre, modelo in modelos.items():
    modelo.fit(X_train, y_train)

    predicciones = modelo.predict(X_test)

    acc = accuracy_score(y_test, predicciones)

    resultados[nombre] = {
        "accuracy": acc,
        "modelo": modelo,
        "predicciones": predicciones
    }

    print(f"{nombre:<35} | Accuracy: {acc:.4f}")


# ==============================
# SELECCIÓN DEL MEJOR MODELO
# ==============================

mejor_nombre = max(resultados, key=lambda x: resultados[x]["accuracy"])
mejor_acc = resultados[mejor_nombre]["accuracy"]
mejor_modelo = resultados[mejor_nombre]["modelo"]
mejores_predicciones = resultados[mejor_nombre]["predicciones"]

print("\n" + "-" * 55)
print(f"Mejor modelo: {mejor_nombre}")
print(f"Accuracy obtenido: {mejor_acc:.4f}")

print("\nMatriz de confusión del mejor modelo:")
print(confusion_matrix(y_test, mejores_predicciones))

print("\nReporte de clasificación del mejor modelo:")
print(classification_report(y_test, mejores_predicciones))


# ==============================
# GUARDAR MEJOR MODELO
# ==============================

joblib.dump(mejor_modelo, ruta_modelo_salida)

print("-" * 55)
print("Mejor modelo guardado en:")
print(ruta_modelo_salida)